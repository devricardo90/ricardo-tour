const requestedLocale = new URLSearchParams(window.location.search).get("locale") || "pt";
const locale = Object.hasOwn(copyByLocale, requestedLocale) ? requestedLocale : "pt";
const copy = copyByLocale[locale];

document.documentElement.lang = copy.lang;
document.title = copy.title;
document.querySelector('meta[name="description"]').content = copy.description;

for (const node of document.querySelectorAll("[data-copy]")) {
  const value = copy[node.dataset.copy];
  if (typeof value !== "string") throw new Error(`Missing ${locale} copy key: ${node.dataset.copy}`);
  node.textContent = value;
}

for (const node of document.querySelectorAll("[data-aria]")) {
  const value = copy[node.dataset.aria];
  if (typeof value !== "string") throw new Error(`Missing ${locale} aria key: ${node.dataset.aria}`);
  node.setAttribute("aria-label", value);
}

for (const node of document.querySelectorAll("[data-placeholder]")) {
  const value = copy[node.dataset.placeholder];
  if (typeof value !== "string") throw new Error(`Missing ${locale} placeholder key: ${node.dataset.placeholder}`);
  node.setAttribute("placeholder", value);
}

for (const node of document.querySelectorAll("[data-alt]")) {
  const value = copy[node.dataset.alt];
  if (typeof value !== "string") throw new Error(`Missing ${locale} image-alt key: ${node.dataset.alt}`);
  node.setAttribute("alt", value);
}

for (let index = 0; index < copy.cardTitles.length; index += 1) {
  document.querySelector(`[data-card-title="${index}"]`).textContent = copy.cardTitles[index];
  document.querySelector(`[data-card-description="${index}"]`).textContent = copy.cardDescriptions[index];
}

document.body.dataset.previewLocale = locale;
